// hreflang-набор: [{ lang: 'kk'|'ru'|'x-default', href }]
function headTags(o) {
  const out = [];
  out.push(`<title>${esc(o.title)}</title>`);
  if (o.description) out.push(`<meta name="description" content="${esc(o.description)}">`);
  out.push(`<meta name="robots" content="${esc(o.robots)}">`);
  if (o.canonical) out.push(`<link rel="canonical" href="${esc(o.canonical)}">`);
  for (const a of o.alternates || []) out.push(`<link rel="alternate" hreflang="${esc(a.lang)}" href="${esc(a.href)}">`);
  // иконки: SVG для современных браузеров, ICO 32/48 для поисковиков и старых, PNG для iOS и Android
  out.push('<link rel="icon" href="/favicon.svg" type="image/svg+xml">');
  out.push('<link rel="icon" href="/favicon.ico" sizes="32x32 48x48">');
  out.push('<link rel="apple-touch-icon" href="/apple-touch-icon.png">');
  // подтверждение прав в Search Console / Вебмастере / Bing — только там, где передано (главная)
  for (const [k, v] of Object.entries(o.verify || {})) if (v) out.push(`<meta name="${k}" content="${esc(v)}">`);
  for (const x of o.extra || []) out.push(x);
  if (o.theme) {
    out.push(`<meta name="theme-color" content="${THEME_LIGHT}" media="(prefers-color-scheme: light)">`);
    out.push(`<meta name="theme-color" content="${THEME_DARK}" media="(prefers-color-scheme: dark)">`);
  }
  // Open Graph
  out.push(`<meta property="og:type" content="${esc(o.ogType || 'website')}">`);
  out.push(`<meta property="og:site_name" content="${esc(o.siteName)}">`);
  out.push(`<meta property="og:title" content="${esc(o.ogTitle || o.title)}">`);
  if (o.ogDescription || o.description) out.push(`<meta property="og:description" content="${esc(o.ogDescription || o.description)}">`);
  if (o.ogUrl) out.push(`<meta property="og:url" content="${esc(o.ogUrl)}">`);
  out.push(`<meta property="og:locale" content="${esc(o.locale)}">`);
  for (const l of o.localeAlt || []) out.push(`<meta property="og:locale:alternate" content="${esc(l)}">`);
  if (o.image) {
    out.push(`<meta property="og:image" content="${esc(o.image)}">`);
    if (/^https:/i.test(o.image)) out.push(`<meta property="og:image:secure_url" content="${esc(o.image)}">`);
    if (o.imageSize) {
      out.push(`<meta property="og:image:type" content="image/jpeg">`);
      out.push(`<meta property="og:image:width" content="${o.imageSize[0]}">`);
      out.push(`<meta property="og:image:height" content="${o.imageSize[1]}">`);
    }
    if (o.imageAlt) out.push(`<meta property="og:image:alt" content="${esc(o.imageAlt)}">`);
  }
  // Twitter Card (берёт og:* как запасной вариант, но title/description/image задаём явно)
  out.push(`<meta name="twitter:card" content="${o.image ? 'summary_large_image' : 'summary'}">`);
  out.push(`<meta name="twitter:title" content="${esc(o.ogTitle || o.title)}">`);
  if (o.ogDescription || o.description) out.push(`<meta name="twitter:description" content="${esc(o.ogDescription || o.description)}">`);
  if (o.image) out.push(`<meta name="twitter:image" content="${esc(o.image)}">`);
  if (o.image && o.imageAlt) out.push(`<meta name="twitter:image:alt" content="${esc(o.imageAlt)}">`);
  for (const ld of o.ld || []) out.push(ldScript(ld));
  if (o.analytics) out.push(o.analytics);
  return out.join('\n');
}
