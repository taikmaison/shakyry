//
// Контракт (его использует services/web/index.js — сигнатуры не менять):
//   homeHead({ config, catalog })                      → HTML для <head> главной (генератор, путь /)
//   templateHead({ config, tpl, fields, url, image })  → HTML для <head> страницы примера шаблона /t/:id (индексируется)
//   inviteHead({ config, data, url, image })           → HTML для <head> личного приглашения /i/:id (noindex, превью для мессенджеров)
//   albumHead({ config, lang, url })                   → HTML для <head> альбома /i/:id/album (noindex)
//   robots({ config })                                 → текст robots.txt
//   sitemap({ config, catalog })                       → XML sitemap
//   page({ config, catalog, path, lang })              → null или { html } — посадочные страницы
// Дополнительно (SEO-блоки, необязательные для index.js):
//   templateExtras({ config, tpl, fields, catalog })   → { top, bottom } — видимый текст страницы /t/:id: полоса с кнопкой
//                                                        «сделать по этому шаблону», крошки, h1, описание, похожие шаблоны
//   siteFooter({ config, catalog, lang })              → HTML футера со ссылками на посадочные (главная, /t/, посадочные)
//   indexableUrls({ config, catalog })                 → список индексируемых адресов (для IndexNow), тот же, что в sitemap
//
// config  — config.json (siteName, siteUrl, defaultLang, whatsapp, payment); все абсолютные адреса строятся от siteUrl.
//   Необязательно: assets { '/landing.css': 'хеш' } — версии статики для ?v=; verify { google, yandex, bing } — коды
//   подтверждения прав (теги только на главной); metrika — номер счётчика Яндекс.Метрики (пусто — без счётчика,
//   на гостевых /i/… счётчика нет никогда).
// catalog — [{ id, category, lang, popularity, preview, price, currency }]
// tpl     — { id, category, lang, price, currency, features[] }; fields — пример { title, name1, name2, date, time, city, address, hosts, invite_text }
//   features — что есть в шаблоне, по компонентам: music, timer, calendar, rsvp, wishes, map, gallery, envelope
// data    — { lang, title, names[], date 'YYYY-MM-DD', time 'HH:MM', category, template_id, city? }
// url     — абсолютный адрес страницы; image — абсолютный адрес картинки-превью или null
//
// Head-функции возвращают фрагмент, который вставляется в <head> вместо <title>
// (charset и viewport в шаблонах страниц уже есть).
