// Страница примера сама по себе — приглашение с демо-данными; поисковику и посетителю из поиска нужны
// заголовок, крошки, описание, цена и ссылки. top — узкая полоса над приглашением (кнопка «сделать по
// этому шаблону»), bottom — блок под приглашением: крошки, h1, описание, похожие шаблоны, ссылки.
// Не выводится для ?raw и ?shot (index.js) и никогда — на гостевых /i/.
function templateExtras({ config, tpl, fields, catalog } = {}) {
  tpl = tpl || {}; fields = fields || {};
  const list = cleanCatalog(catalog);
  const id = Number(tpl.id);
  if (!Number.isSafeInteger(id) || id <= 0) return { top: '', bottom: '' };
  const lang = tpl.lang === 'ru' ? 'ru' : 'kz';
  const cat = catOf(tpl.category), U = uiFor(lang, cat), L = cat[lang], lc = landingCat(tpl.category);
  const price = tpl.price != null && Number.isFinite(Number(tpl.price)) ? money(Number(tpl.price), tpl.currency || 'KZT') : null;
  const use = `/?template=${id}`;
  const h1 = U.tplH1(inviteWord(cat, lang), id);
  // свидание: дату выбирает сама девушка в календаре, ответ приходит в Telegram — общий текст здесь неверен
  const lead = tpl.category === 'svidanie'
    ? (lang === 'ru'
      ? `Шаблон №${id} — ${lcFirst(L.name)}, ${U.inLang[lang]}. Впишите её имя, время и место — дату она выберет сама в календаре, а ответ придёт вам в Telegram.`
      : `№${id} үлгі — ${lcFirst(L.name)}, ${U.inLang[lang]}. Қыздың есімін, уақыт пен орынды жазыңыз — күнді ол күнтізбеден өзі таңдайды, жауабы Telegram-ға келеді.`)
    : U.tplLead(L.name, U.inLang[lang]).replace('{num}', String(id));
  const feats = featureList(tpl, lang);
  const sampleTxt = cat.sober ? '' : oneLine(fields.invite_text || '', 300);
  // похожие: тот же повод и язык, по популярности; если мало — тот же повод на другом языке
  const same = list.filter(t => t.id !== id && landingCat(t.category) === lc && lc).sort(byPopularity);
  const related = [...same.filter(t => t.lang === lang), ...same.filter(t => t.lang !== lang)].slice(0, 6);
  // соседи по номеру — цепочка по всему каталогу
  const ids = list.map(t => t.id).sort((a, b) => a - b), pos = ids.indexOf(id);
  const prev = pos > 0 ? ids[pos - 1] : null, next = pos >= 0 && pos < ids.length - 1 ? ids[pos + 1] : null;
  const allOf = lc ? `<a class="btn btn-alt" href="${catPath(lang, lc)}">${esc(U.allOf(lc[lang].name))} (${same.length + 1})</a>` : '';

  const top = `<div class="tbar" lang="${LANG[lang].code}"><span class="tbar-t"><b>№${id}</b> · ${esc(L.invite)}${price ? ` · ${esc(price)}` : ''}</span><a class="tbar-btn" href="${use}" rel="nofollow">${esc(U.useShort)}</a></div>`;
  const bottom = `<footer class="tfoot" lang="${LANG[lang].code}">
<div class="tfoot-in">
${crumbsHtml(U, templateCrumbs(config, { ...tpl, id }, lang))}
<h1>${esc(h1)}</h1>
<p class="lead">${esc(lead)}</p>
${sampleTxt ? `<p class="sample"><b>${esc(U.sampleText)}:</b> «${esc(sampleTxt)}»</p>` : ''}
${feats.length ? `<p class="feat"><b>${esc(U.featH)}:</b> ${esc(feats.join(', '))}.</p>` : ''}
<p class="tprice">${esc(U.priceFree)}${price ? ' ' + esc(U.priceText.replace('{price}', () => price)) : ''}</p>
<p class="cta"><a class="btn btn-main" href="${use}" rel="nofollow">${esc(U.useTpl)}</a>${allOf}</p>
${related.length ? `<section><h2>${esc(U.related)}</h2>${grid(related, lang, 6)}</section>` : ''}
<p class="tnav">${prev ? `<a href="/t/${prev}">← ${esc(U.prevTpl)} №${prev}</a>` : ''}${prev && next ? ' · ' : ''}${next ? `<a href="/t/${next}">${esc(U.nextTpl)} №${next} →</a>` : ''}</p>
</div>
${siteFooter({ config, catalog: list, lang, compact: true })}
</footer>`;
  return { top, bottom };
}

