function catNav(lang, cats, current) {
  return `<ul class="cats">${cats.map(({ cat, items }) => {
    const cur = cat === current ? ' aria-current="page"' : '';
    return `<li><a href="${catPath(lang, cat)}"${cur}>${esc(cat[lang].name)} <span>${items.length}</span></a></li>`;
  }).join('')}</ul>`;
}

// хлебные крошки: видимые и в JSON-LD — один массив [[название, путь], …]
function crumbsHtml(U, crumbs) {
  return `<nav class="crumbs" aria-label="${esc(U.crumbsLabel)}"><ol>${crumbs.map(([label, href], i) =>
    i === crumbs.length - 1 ? `<li aria-current="page">${esc(label)}</li>` : `<li><a href="${esc(href)}">${esc(label)}</a></li>`).join('')}</ol></nav>`;
}

// Футер со ссылками на все посадочные: главная (lang=null — оба языка), посадочные и /t/ (язык страницы).
// Один и тот же низ у всех страниц — поисковик с любой из них доходит до каждого повода.
function siteFooter({ config, catalog, lang, compact } = {}) {
  const list = cleanCatalog(catalog);
  const cats = landingCats(list);
  const name = siteName(config);
  const langs = lang ? [lang] : ['kz', 'ru'];
  const navs = langs.map(l => {
    const U = UI[l];
    const head = l === 'kz' ? 'Онлайн шақыру билеті қазақша' : 'Онлайн-приглашения на русском';
    const items = compact ? cats.slice(0, 10) : cats;
    return `<nav aria-label="${esc(U.occasions)}" lang="${LANG[l].code}"><b><a href="${hubPath(l)}" hreflang="${LANG[l].code}">${esc(head)}</a></b>`
      + `<ul class="cats">${items.map(({ cat, items: ts }) => `<li><a href="${catPath(l, cat)}">${esc(cat[l].name)} <span>${ts.length}</span></a></li>`).join('')}`
      + (compact && cats.length > items.length ? `<li><a href="${hubPath(l)}">…</a></li>` : '') + `</ul></nav>`;
  }).join('\n');
  const U = UI[lang || defLang(config)];
  const other = lang ? (lang === 'kz' ? 'ru' : 'kz') : null;
  const links = [
    `<a href="/">${esc(name)}</a>`,
    ...(other ? [`<a href="${hubPath(other)}" lang="${LANG[other].code}" hreflang="${LANG[other].code}">${esc(LANG[other].name)}</a>`] : []),
    ...(lang ? [`<a href="${aboutPath(lang)}">${esc(U.aboutLink)}</a>`]
      : ['kz', 'ru'].map(l => `<a href="${aboutPath(l)}" hreflang="${LANG[l].code}" lang="${LANG[l].code}">${esc(UI[l].aboutLink)}</a>`)),
    ...(config && config.whatsapp ? [`<a href="https://wa.me/${esc(config.whatsapp)}" rel="nofollow noopener" target="_blank">WhatsApp ${esc(waPretty(config.whatsapp))}</a>`] : []),
  ];
  return `<footer class="sitefoot wrap"${lang ? ` lang="${LANG[lang].code}"` : ''}>
${navs}
<p>${esc(U.footer)} · ${esc(U.region)}. ${links.join(' · ')}</p>
</footer>`;
}

