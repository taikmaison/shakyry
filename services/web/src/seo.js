// экранирование для текста и значений атрибутов (атрибуты всегда в двойных кавычках)
const esc = s => String(s ?? '').replace(/[&<>"']/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]));

// JSON внутри <script>: никаких «</script>», «<!--», «&» и разделителей строк U+2028/2029
const safeJson = obj => JSON.stringify(obj)
  .replace(/</g, '\\u003c').replace(/>/g, '\\u003e').replace(/&/g, '\\u0026')
  .replace(/\u2028/g, '\\u2028').replace(/\u2029/g, '\\u2029');
const ldScript = obj => `<script type="application/ld+json">${safeJson(obj)}</script>`;

// базовый адрес сайта без завершающего слеша
const base = config => String((config && config.siteUrl) || '').trim().replace(/\/+$/, '');
// абсолютный адрес от siteUrl; уже абсолютные (http/https) оставляем как есть
function abs(config, p) {
  const s = String(p ?? '');
  if (/^https?:\/\//i.test(s)) return s;
  return base(config) + (s.startsWith('/') ? s : '/' + s);
}
const siteName = config => String((config && config.siteName) || 'Шақыру');
// обрезка по границе слова: «…ссылка для гостей в…», а не «…в WhatsA…»
const oneLine = (s, max = 200) => {
  const t = String(s ?? '').replace(/\s+/g, ' ').trim();
  if (t.length <= max) return t;
  let cut = t.slice(0, max - 1);
  if (/\S/.test(t[max - 1])) { const w = cut.replace(/\s*\S*$/, ''); if (w) cut = w; }
  return cut.replace(/[\s,:;—–-]+$/, '') + '…';
};
const lcFirst = s => s ? s[0].toLocaleLowerCase() + s.slice(1) : s;
// «Заголовок | Бренд», если влезает в 60 знаков сниппета; иначе только заголовок (поисковик сам допишет имя сайта)
const fitTitle = (main, brand) => (main.length + brand.length + 3 <= 60 ? `${main} | ${brand}` : main);
// адрес статики с версией (?v=хеш → долгий кеш); без версии в config — как есть
const asset = (config, p) => (config && config.assets && config.assets[p] ? `${p}?v=${config.assets[p]}` : p);
// стили посадочных вставляются в HTML (один запрос меньше); файл читается один раз при старте
let LANDING_CSS = '';
try { LANDING_CSS = fs.readFileSync(path.join(__dirname, '..', 'public', 'landing.css'), 'utf8'); } catch { /* без файла — без стилей */ }

// русские числительные: 1 шаблон, 2 шаблона, 5 шаблонов
function plural(n, one, few, many) {
  const a = Math.abs(n) % 100, b = a % 10;
  if (a > 10 && a < 20) return many;
  if (b === 1) return one;
  if (b >= 2 && b <= 4) return few;
  return many;
}

