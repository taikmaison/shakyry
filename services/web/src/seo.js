const MONTHS = {
  kz: ['қаңтар', 'ақпан', 'наурыз', 'сәуір', 'мамыр', 'маусым', 'шілде', 'тамыз', 'қыркүйек', 'қазан', 'қараша', 'желтоқсан'],
  ru: ['января', 'февраля', 'марта', 'апреля', 'мая', 'июня', 'июля', 'августа', 'сентября', 'октября', 'ноября', 'декабря'],
};
const WEEKDAYS = {
  kz: ['жексенбі', 'дүйсенбі', 'сейсенбі', 'сәрсенбі', 'бейсенбі', 'жұма', 'сенбі'],
  ru: ['воскресенье', 'понедельник', 'вторник', 'среда', 'четверг', 'пятница', 'суббота'],
};

// «2026 жылғы 12 желтоқсан, сенбі, сағат 18:00» / «12 декабря 2026, суббота, в 18:00»
function formatWhen(lang, date, time) {
  const parts = [];
  const m = /^(\d{4})-(\d{2})-(\d{2})$/.exec(String(date || ''));
  if (m) {
    const y = +m[1], mo = +m[2], d = +m[3];
    const dt = new Date(Date.UTC(y, mo - 1, d));
    if (dt.getUTCFullYear() === y && dt.getUTCMonth() === mo - 1 && dt.getUTCDate() === d) {
      const wd = WEEKDAYS[lang][dt.getUTCDay()];
      parts.push(lang === 'ru' ? `${d} ${MONTHS.ru[mo - 1]} ${y}, ${wd}` : `${y} жылғы ${d} ${MONTHS.kz[mo - 1]}, ${wd}`);
    }
  }
  const t = /^([01]\d|2[0-3]):([0-5]\d)$/.exec(String(time || ''));
  if (t) parts.push(lang === 'ru' ? `в ${t[0]}` : `сағат ${t[0]}`);
  return parts.join(', ');
}

function inviteHead({ config, data, url, image } = {}) {
  data = data || {};
  const lang = data.lang === 'ru' ? 'ru' : 'kz';
  const cat = catOf(data.category);
  const name = siteName(config);
  const names = (Array.isArray(data.names) ? data.names : []).map(x => oneLine(x, 60)).filter(Boolean);
  const joined = names.join(' & ');
  const ttl = oneLine(data.title, 100);
  // og:title: «Имена — Название»; если в названии уже есть имена — только название
  let title;
  if (ttl && joined) title = names.every(nm => ttl.includes(nm)) ? ttl : `${joined} — ${ttl}`;
  else title = ttl || joined || cat[lang].invite;
  title = oneLine(title, 120);

  let when = formatWhen(lang, data.date, data.time);
  // без даты (свидание: дату выбирает гость) время стоит первым — с большой буквы
  if (!/^\d{4}-\d{2}-\d{2}$/.test(String(data.date || ''))) when = when.replace(/^в /, 'В ').replace(/^сағат /, 'Сағат ');
  const city = oneLine(data.city, 60);
  const lead = data.category === 'svidanie' ? (lang === 'ru' ? 'Приглашаю тебя!' : 'Сені шақырамын!') : lang === 'ru' ? 'Приглашаем вас!' : 'Сізді шақырамыз!';
  const description = [lead, [when, city].filter(Boolean).join(' · ')].filter(Boolean).join(' ');

  const tid = Number(data.template_id);
  const img = image ? abs(config, image) : Number.isSafeInteger(tid) && tid > 0 ? abs(config, ogJpg(tid)) : null;
  // снимок приглашения (сервис shots) того же размера, что примеры шаблонов
  const imageSize = img && /\/(previews\/\d+|og\/i\/[a-z0-9]+)\.jpe?g(\?|$)/i.test(img) ? [OG_W, OG_H] : null;

  return headTags({
    title, description, robots: NOINDEX, siteName: name, ogUrl: url ? abs(config, url) : '',
    locale: LANG[lang].locale, image: img, imageSize, imageAlt: title,
  });
}

