// ---------------------------------------------------------------- sitemap.xml

const xmlEsc = s => String(s ?? '').replace(/[&<>"']/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&apos;' }[c]));

function sitemap({ config, catalog } = {}) {
  const list = cleanCatalog(catalog);
  const urls = [];
  const alt = links => links.map(a => `<xhtml:link rel="alternate" hreflang="${xmlEsc(a.lang)}" href="${xmlEsc(a.href)}"/>`).join('');
  const add = (loc, extra = '') => urls.push(`<url><loc>${xmlEsc(loc)}</loc>${extra}</url>`);

  // главная и обзорные страницы — один hreflang-кластер
  const hubAlt = alt(hubAlternates(config));
  add(abs(config, '/'), hubAlt);
  for (const lang of ['kz', 'ru']) add(abs(config, hubPath(lang)), hubAlt);
  // страницы поводов
  for (const { cat } of landingCats(list)) {
    const a = alt(catAlternates(config, cat));
    for (const lang of ['kz', 'ru']) add(abs(config, catPath(lang, cat)), a);
  }
  // о сервисе
  const aboutAlt = alt(aboutAlternates(config));
  for (const lang of ['kz', 'ru']) add(abs(config, aboutPath(lang)), aboutAlt);
  // примеры шаблонов с картинкой
  for (const t of list.slice().sort((a, b) => a.id - b.id))
    add(abs(config, `/t/${t.id}`), `<image:image><image:loc>${xmlEsc(abs(config, ogJpg(t.id)))}</image:loc></image:image>`);

  return '<?xml version="1.0" encoding="UTF-8"?>\n'
    + '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9"'
    + ' xmlns:image="http://www.google.com/schemas/sitemap-image/1.1"'
    + ' xmlns:xhtml="http://www.w3.org/1999/xhtml">\n'
    + urls.join('\n') + '\n</urlset>\n';
}

