// только корректные записи: целый id, известный язык
function cleanCatalog(catalog) {
  if (!Array.isArray(catalog)) return [];
  const seen = new Set(), out = [];
  for (const t of catalog) {
    if (!t || typeof t !== 'object') continue;
    const id = Number(t.id);
    if (!Number.isSafeInteger(id) || id <= 0 || seen.has(id)) continue;
    seen.add(id);
    out.push({ id, category: String(t.category ?? ''), lang: t.lang === 'ru' ? 'ru' : 'kz', popularity: Number(t.popularity) || 0, preview: t.preview,
      ...(Number.isFinite(t.price) ? { price: t.price, currency: /^[A-Z]{3}$/.test(t.currency) ? t.currency : 'KZT' } : {}) });
  }
  return out;
}
const byPopularity = (a, b) => b.popularity - a.popularity || a.id - b.id;

// поводы с посадочными страницами: только известные и с шаблонами
function landingCats(list) {
  const groups = new Map();
  for (const t of list) {
    const c = CAT_BY_KEY.get(t.category);
    if (!c || c.landing === false) continue;
    if (!groups.has(c)) groups.set(c, []);
    groups.get(c).push(t);
  }
  // порядок — как в CATS (сначала самые востребованные поводы)
  return CATS.filter(c => groups.has(c)).map(c => ({ cat: c, items: groups.get(c).sort(byPopularity) }));
}

