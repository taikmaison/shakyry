// «от 3 500 ₸» по каталогу (одна цена у всех — без «от»)
function priceFrom(list, lang) {
  const ps = list.map(t => t.price).filter(Number.isFinite);
  if (!ps.length) return null;
  const min = Math.min(...ps), cur = (list.find(t => t.price === min) || {}).currency;
  const s = money(min, cur);
  return ps.every(p => p === min) ? s : (lang === 'ru' ? `от ${s}` : `${s}-ден бастап`);
}
