// страница повода /kz/<slug>/ или /ru/<slug>/
function catPage(config, lang, list, entry) {
  const { cat, items } = entry;
  const U = uiFor(lang, cat), L = cat[lang], other = lang === 'kz' ? 'ru' : 'kz';
  const cats = landingCats(list);
  const own = items.filter(t => t.lang === lang), foreign = items.filter(t => t.lang !== lang);
  const ordered = [...own, ...foreign];
  const price = priceFrom(items, lang);
  // вопросы повода — первыми; FAQPage размечаем только их (общие размечены один раз на /kz/ и /ru/)
  const generic = cat.sober ? U.faq.filter(([q]) => !SOBER_SKIP[lang].test(q)) : U.faq;
  const ownFaq = withPrice(L.faq || [], price), faq = [...ownFaq, ...withPrice(generic, price)];
  const canonical = abs(config, catPath(lang, cat));
  const crumbs = [[U.home, '/'], [U.hub, hubPath(lang)], [L.name, catPath(lang, cat)]];
  const ld = {
    '@context': 'https://schema.org',
    '@graph': [
      orgNode(config), websiteNode(config),
      breadcrumbLd(crumbs.map(([n, h]) => [n, abs(config, h)])),
      itemListLd(config, L.h1, ordered),
      ...(ownFaq.length ? [faqLd(ownFaq)] : []),
    ],
  };
  const groups = [];
  if (own.length) groups.push(`<h3>${esc(U.tplIn[lang])} <span class="count">${own.length}</span></h3>${grid(own, lang)}`);
  else groups.push(`<p class="note">${esc(U.onlyOther)}</p>`);
  if (foreign.length) groups.push(`<h3>${esc(U.tplIn[other])} <span class="count">${foreign.length}</span></h3>${grid(foreign, lang, own.length)}`);
  // цена — в сниппет, если помещается целиком (иначе описание повода как есть)
  const priceNote = price ? (lang === 'ru' ? ` Предпросмотр бесплатно, публикация — ${price}.` : ` Алдын ала қарау тегін, жариялау — ${price}.`) : '';
  const description = (L.desc + priceNote).length <= 160 ? L.desc + priceNote : L.desc;

  const body = `<h1>${esc(L.h1)}</h1>
<p class="lead">${esc(L.desc)}</p>
<p class="cta"><a class="btn btn-main" href="#templates">${esc(U.ctaMain)}</a><a class="btn btn-alt" href="/">${esc(U.ctaGen)}</a></p>
<section class="text">${paras(L.intro)}</section>
<section id="templates"><h2>${esc(U.templates)}: ${esc(L.name)} <span class="count">${items.length}</span></h2>${groups.join('\n')}</section>
<section><h2>${esc(U.tipsH)}</h2><ul class="tips">${L.tips.map(x => `<li>${esc(x)}</li>`).join('')}</ul></section>
${priceSection(U, price)}
${howSection(U)}
${faqSection(U, faq)}
<section><h2>${esc(U.otherOccasions)}</h2>${catNav(lang, cats, cat)}</section>`;
  return layout({
    config, catalog: list, lang, title: fitTitle(U.catTitle(L, items.length), siteName(config)), description, canonical,
    alternates: catAlternates(config, cat), altHref: catPath(other, cat), og: ogFromList(config, ordered, lang), ld, crumbs, body,
  });
}

// о сервисе /kz/about/ и /ru/about/: цена, оплата, проверка, контакты (тексты — UI.*.about)
function aboutPage(config, lang, list) {
  const U = UI[lang], A = U.about, other = lang === 'kz' ? 'ru' : 'kz';
  const price = priceFrom(list, lang);
  const wa = config && config.whatsapp ? waPretty(config.whatsapp) : '';
  const n = list.length;
  const nText = lang === 'ru' ? `${n} ${plural(n, 'шаблон', 'шаблона', 'шаблонов')}` : `${n} үлгі`;
  // замены функциями: «$» в реквизитах и цене ничего не значит
  const fill = s => s.replace('{n}', () => nText).replace('{price}', () => price || (lang === 'ru' ? 'цена указана в генераторе' : 'бағасы генераторда көрсетілген'))
    .replace('{payment}', () => (config && config.payment ? ` (${config.payment})` : '')).replace('{wa}', () => wa || (lang === 'ru' ? 'номер указан в генераторе' : 'нөмірі генераторда көрсетілген'));
  const canonical = abs(config, aboutPath(lang));
  const crumbs = [[U.home, '/'], [U.hub, hubPath(lang)], [A.title, aboutPath(lang)]];
  const ld = { '@context': 'https://schema.org', '@graph': [orgNode(config), websiteNode(config), breadcrumbLd(crumbs.map(([n, h]) => [n, abs(config, h)]))] };
  const body = `<h1>${esc(A.h1)}</h1>
<section class="text">${paras(A.paras.map(fill))}</section>
${priceSection(U, price)}
${howSection(U)}
${wa ? `<p class="cta"><a class="btn btn-main" href="https://wa.me/${esc(config.whatsapp)}" rel="nofollow noopener" target="_blank">WhatsApp ${esc(wa)}</a><a class="btn btn-alt" href="/">${esc(U.ctaGen)}</a></p>` : `<p class="cta"><a class="btn btn-main" href="/">${esc(U.ctaGen)}</a></p>`}`;
  return layout({
    config, catalog: list, lang, title: fitTitle(A.title, siteName(config)), description: A.desc, canonical,
    alternates: aboutAlternates(config), altHref: aboutPath(other), og: ogFromList(config, list, lang), ld, crumbs, body,
  });
}

// path — путь из URL; lang — язык из URL или null (язык берётся из префикса пути, он главнее)
function page({ config, catalog, path, lang } = {}) {
  let p = String(path ?? '').split(/[?#]/)[0];
  try { p = decodeURIComponent(p); } catch { return null; }
  const m = /^\/(kz|ru)(?:\/([a-z0-9-]+))?\/?$/.exec(p.toLowerCase());
  if (!m) return null;
  const l = m[1];
  const list = cleanCatalog(catalog);
  if (!m[2]) return { html: hubPage(config, l, list) };
  if (m[2] === 'about') return { html: aboutPage(config, l, list) };
  const cat = CAT_BY_SLUG.get(m[2]);
  if (!cat) return null;
  const entry = landingCats(list).find(e => e.cat === cat);
  if (!entry) return null;   // повод без шаблонов — страницы нет
  return { html: catPage(config, l, list, entry) };
}

