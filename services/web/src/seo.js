function breadcrumbLd(items) {
  return {
    '@type': 'BreadcrumbList',
    itemListElement: items.map(([name, item], i) => ({ '@type': 'ListItem', position: i + 1, name, item })),
  };
}
function itemListLd(config, name, items) {
  return {
    '@type': 'ItemList', name, numberOfItems: items.length,
    itemListElement: items.map((t, i) => ({ '@type': 'ListItem', position: i + 1, url: abs(config, `/t/${t.id}`) })),
  };
}
function faqLd(faq) {
  return {
    '@type': 'FAQPage',
    mainEntity: faq.map(([q, a]) => ({ '@type': 'Question', name: q, acceptedAnswer: { '@type': 'Answer', text: a } })),
  };
}

// 3500 → «3 500 ₸»
function money(price, currency = 'KZT') {
  try { return new Intl.NumberFormat('ru-RU', { style: 'currency', currency, currencyDisplay: 'narrowSymbol', maximumFractionDigits: 0 }).format(price); }
  catch { return `${price} ${currency}`; }
}
// WhatsApp для заказа индивидуального дизайна: 77780122500 → «+7 778 012 25 00»
const waPretty = wa => wa.length === 11 ? `+${wa[0]} ${wa.slice(1, 4)} ${wa.slice(4, 7)} ${wa.slice(7, 9)} ${wa.slice(9)}` : '+' + wa;

// карточка шаблона: превью → пример /t/<id>, кнопка → генератор с выбранным шаблоном.
// i — номер карточки на странице: первые грузятся сразу (первый экран), остальные лениво
function card(t, lang, i = 99) {
  const U = UI[lang], c = catOf(t.category);
  const alt = lang === 'ru'
    ? `${c.ru.invite}: шаблон №${t.id}, ${U.inLang[t.lang]}`
    : `${inviteWord(c, 'kz')}: №${t.id} үлгі, ${U.inLang[t.lang]}`;
  const load = i < 6 ? `loading="eager"${i === 0 ? ' fetchpriority="high"' : ''}` : 'loading="lazy"';
  return `<li class="card">`
    + `<a class="pic" href="/t/${t.id}"><img src="${esc(previewSrc(t))}" width="${PREVIEW_W}" height="${PREVIEW_H}" ${load} decoding="async" alt="${esc(alt)}"></a>`
    + `<div class="meta"><a class="num" href="/t/${t.id}">№${t.id}</a>${t.price != null ? `<span class="price">${esc(money(t.price, t.currency))}</span>` : ''}<span class="badge">${esc(U.badge[t.lang])}</span></div>`
    + `<div class="acts"><a href="/t/${t.id}">${esc(U.view)}</a><a class="go" href="/?template=${t.id}" rel="nofollow">${esc(U.use)}</a></div>`
    + `</li>`;
}
